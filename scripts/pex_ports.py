#!/usr/bin/env python3
"""Finish a Magic parasitic-extraction netlist for simulation:

    scripts/pex_ports.py RAW.spice REF.spice OUT.spice none|c|rc

RAW is ext2spice's output for a flattened copy of the cell (.subckt name
<cell>_flat), REF the cell's LVS schematic netlist from xschem
(lvs/schematic/<cell>.spice). OUT gets:
  - the .subckt renamed back to <cell>
  - the ports in REF's order. Magic orders ports by the layout labels' port
    numbers, xschem by the symbol's pin order, and instance lines connect by
    position, so without this the extracted netlist can't replace the
    schematic one under the symbol. The two port lists must be the same set.
  - zero-valued caps (ext2spice cthresh 0) dropped, and Magic's
    '$ **FLOATING' tags on substrate caps removed (Netgen reads the '$' as an
    element)
  - the checkout-dependent first line ('* NGSPICE file created from ...')
    replaced by a header naming the source
Same rules as lvdig's scripts/gen_lib_netlist.py, for one cell.
"""
import re
import sys


def one_subckt(path, text):
    found = re.findall(r'^\.subckt (\S+)(.*)$', text, re.M)
    if len(found) != 1:
        sys.exit(f'{path}: expected one .subckt, found {len(found)}')
    return found[0][0], found[0][1].split()


def main(raw, ref, out, mode):
    rtext = open(raw).read()
    name, have = one_subckt(raw, rtext)
    cell = re.sub(r'_flat$', '', name)
    rname, want = one_subckt(ref, open(ref).read())
    if rname != cell:
        sys.exit(f'{raw}: cell {cell} but {ref} has {rname}')
    if sorted(have) != sorted(want):
        sys.exit(f'{raw}: ports {have} differ from {ref}: {want}')
    lines = []
    for ln in rtext.splitlines():
        if ln.startswith('* NGSPICE file created from'):
            continue
        if ln.startswith('.subckt '):
            ln = f'.subckt {cell} ' + ' '.join(want)
        ln = re.sub(r'\s+\$\s*\*\*FLOATING\s*$', '', ln)
        if re.fullmatch(r'C\d+ \S+ \S+ 0', ln):
            continue
        lines.append(ln)
    desc = {'none': 'devices only',
            'c': 'parasitic C (ext2spice cthresh 0), no R',
            'rc': 'parasitic R (extresist, tolerance 10) and C (cthresh 0)'}[mode]
    head = [f'* {cell}: layout-extracted netlist, {desc}.',
            f'* Generated by `make pex CELL={cell} PEX={mode}` from mag/{cell}.mag; don\'t edit.',
            '* Magic on a flattened copy of the cell; ports in the schematic\'s order',
            f'* ({ref}), so it can replace the schematic netlist under the symbol.']
    with open(out, 'w') as f:
        f.write('\n'.join(head + lines).rstrip('\n') + '\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    a = sys.argv[1:]
    if len(a) != 4 or a[3] not in ('none', 'c', 'rc'):
        sys.exit('usage: pex_ports.py RAW.spice REF.spice OUT.spice none|c|rc')
    main(*a)
